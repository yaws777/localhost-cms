// restockReport.jsx
// Automated restock report for the office: what is low, critical, out of stock or expiring,
// how much the next 30 days are expected to need, and how much to order.
import React, { useState, useEffect, useCallback, useMemo } from 'react';
import { useOutletContext } from 'react-router-dom';
import { PackageCheck, Printer, RefreshCw, History, X, AlertTriangle, CheckCircle2, Clock } from 'lucide-react';
import { useAlert } from '../../context/AlertContext';
import stiLogo from '../../assets/sti-logof.png';
import { formatDate, formatTime } from '../../utils/datetime';
import '../../styles/nurse/RestockReport.css';

const API = 'http://localhost:3001';

const STATUS_ORDER = { 'Out of stock': 0, 'Critical': 1, 'Low': 2, 'Adequate': 3 };
const STATUS_CLASS = { 'Out of stock': 'out', 'Critical': 'critical', 'Low': 'low', 'Adequate': 'ok' };

const TRIGGER_LABEL = { 'Scheduled': 'Daily 7:00 AM', 'Stock change': 'Stock change', 'Manual': 'Generated by staff' };

const escapeHtml = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// live medicines and saved report items have different field names: use one shape for both
const fromLive = (m) => ({
    id: m.medicine_id, name: m.name, form: m.dosage_form, unit: m.unit_label, status: m.status,
    stock: m.usable_stock, total: m.total_stock, low: m.low_stock_level, critical: m.critical_stock_level, adequate: m.adequate_stock_level,
    forecast: m.forecast_30d, suggested: m.suggested_qty, toAdequate: m.to_adequate_qty,
    nearestExpiry: m.nearest_expiry, expiring: m.expiring_stock, expired: m.expired_stock
});

const fromItem = (i) => ({
    id: `${i.report_id}-${i.item_id}`, name: i.medicine_name, form: i.dosage_form, unit: i.unit_label, status: i.status,
    stock: Number(i.usable_stock), total: Number(i.total_stock), low: i.low_level, critical: i.critical_level, adequate: i.adequate_level,
    forecast: Number(i.forecast_30d), suggested: i.suggested_qty, toAdequate: i.to_adequate_qty,
    nearestExpiry: i.nearest_expiry, expiring: i.expiring_stock, expired: i.expired_stock
});

const stamp = (s) => (s ? `${formatDate(String(s).slice(0, 10))}, ${formatTime(String(s).replace(' ', 'T'))}` : '');

const printRestock = (title, generatedAt, rows, preparedBy, onBlocked) => {
    const w = window.open('', '_blank', 'width=1100,height=800');
    if (!w) { onBlocked(); return; }
    const body = rows.map((r) => `
        <tr>
            <td><strong>${escapeHtml(r.name)}</strong><br/><span class="muted">${escapeHtml(r.form || '')}</span></td>
            <td class="s-${STATUS_CLASS[r.status]}">${escapeHtml(r.status)}</td>
            <td>${r.stock}</td>
            <td>${r.low} / ${r.critical} / ${r.adequate}</td>
            <td>${r.forecast}</td>
            <td><strong>${r.suggested}</strong> ${escapeHtml(r.unit || '')}</td>
            <td>${r.toAdequate}</td>
            <td>${r.nearestExpiry ? escapeHtml(formatDate(String(r.nearestExpiry).slice(0, 10))) : '-'}</td>
            <td>${r.expiring ? `${r.expiring} expiring soon` : ''}${r.expiring && r.expired ? '<br/>' : ''}${r.expired ? `<span class="s-out">${r.expired} expired</span>` : ''}${!r.expiring && !r.expired ? '-' : ''}</td>
        </tr>`).join('');

    w.document.write(`<!DOCTYPE html><html><head><title>${escapeHtml(title)}</title><style>
        body { font-family: Arial, Helvetica, sans-serif; margin: 25px; color: #0f172a; }
        .head { display: flex; align-items: center; border-bottom: 2px solid #0056b3; padding-bottom: 12px; margin-bottom: 14px; }
        .head img { height: 60px; margin-right: 20px; }
        .head h2 { margin: 0; font-size: 20px; color: #1e3a8a; } .head p { margin: 4px 0 0; font-size: 13px; color: #475569; }
        .meta { display: flex; justify-content: space-between; font-size: 13px; color: #475569; margin-bottom: 14px; }
        table { width: 100%; border-collapse: collapse; font-size: 12px; }
        th { background: #f1f5f9; text-align: left; padding: 8px; border: 1px solid #cbd5e1; }
        td { padding: 7px 8px; border: 1px solid #e2e8f0; vertical-align: top; }
        .muted { color: #64748b; } .s-out { color: #b91c1c; font-weight: 700; } .s-critical { color: #c2410c; font-weight: 700; } .s-low { color: #a16207; font-weight: 700; } .s-ok { color: #15803d; }
        .note { font-size: 11px; color: #64748b; margin-top: 10px; }
        .sign { margin-top: 50px; display: flex; justify-content: space-between; font-size: 13px; }
        .sign div { width: 40%; border-top: 1px solid #0f172a; padding-top: 6px; text-align: center; }
        @media print { body { margin: 0; } }
    </style></head><body>
        <div class="head"><img src="${stiLogo}" alt="STI Logo" /><div><h2>STI COLLEGE BALIUAG</h2><p>School Clinic - Medicine Restock Report</p></div></div>
        <div class="meta"><span><strong>${escapeHtml(title)}</strong></span><span>Generated: ${escapeHtml(generatedAt)}</span></div>
        <table>
            <thead><tr><th>Medicine</th><th>Status</th><th>Usable stock</th><th>Low / Critical / Adequate level</th><th>Next 30 days (forecast)</th><th>Suggested restock</th><th>To reach adequate</th><th>Nearest expiry</th><th>Expiry</th></tr></thead>
            <tbody>${body || '<tr><td colspan="9">Every medicine is adequately stocked and nothing is expiring soon.</td></tr>'}</tbody>
        </table>
        <p class="note">Usable stock leaves out expired batches. Suggested restock = forecast demand for the next 30 days + critical level - usable stock (never below 0).</p>
        <div class="sign"><div>${escapeHtml(preparedBy || 'School Nurse')}<br/>Prepared by</div><div>Office / Purchasing<br/>Received by</div></div>
        <script>window.onload = function () { window.print(); };</script>
    </body></html>`);
    w.document.close();
};

const RestockTable = ({ rows }) => (
    <div className="table-wrap-rr">
        <table className="table-rr">
            <thead>
                <tr>
                    <th>Medicine</th><th>Status</th><th>Usable stock</th><th>Low / Crit / Adequate</th>
                    <th>Next 30 days</th><th>Suggested restock</th><th>To reach adequate</th><th>Nearest expiry</th><th>Expiry</th>
                </tr>
            </thead>
            <tbody>
                {rows.length === 0 ? (
                    <tr><td colSpan="9" className="empty-rr">
                        <CheckCircle2 size={20} /> Every medicine is adequately stocked and nothing is expiring soon.
                    </td></tr>
                ) : rows.map((r) => (
                    <tr key={r.id}>
                        <td><strong>{r.name}</strong><div className="muted-rr">{r.form}</div></td>
                        <td><span className={`badge-rr badge-${STATUS_CLASS[r.status]}-rr`}>{r.status}</span></td>
                        <td><strong>{r.stock}</strong>{r.total !== r.stock && <div className="muted-rr">{r.total} incl. expired</div>}</td>
                        <td className="muted-rr">{r.low} / {r.critical} / {r.adequate}</td>
                        <td>{r.forecast}</td>
                        <td><strong className="suggest-rr">{r.suggested}</strong> <span className="muted-rr">{r.unit}</span></td>
                        <td>{r.toAdequate}</td>
                        <td>{r.nearestExpiry ? formatDate(String(r.nearestExpiry).slice(0, 10)) : '-'}</td>
                        <td>
                            {r.expiring > 0 && <div className="expiry-soon-rr">{r.expiring} expiring within 30 days</div>}
                            {r.expired > 0 && <div className="expiry-gone-rr">{r.expired} expired</div>}
                            {!r.expiring && !r.expired && '-'}
                        </td>
                    </tr>
                ))}
            </tbody>
        </table>
    </div>
);

const RestockReport = () => {
    const { firstName, lastName, userId } = useOutletContext() || {};
    const { showAlert } = useAlert();
    const nurseName = `${firstName || ''} ${lastName || ''}`.trim();

    const [live, setLive] = useState({ summary: null, medicines: [], generated_at: '' });
    const [history, setHistory] = useState([]);
    const [loading, setLoading] = useState(true);
    const [generating, setGenerating] = useState(false);
    const [filter, setFilter] = useState('all');
    const [openReport, setOpenReport] = useState(null);

    const load = useCallback(async () => {
        try {
            const [statusRes, histRes] = await Promise.all([
                fetch(`${API}/api/medicine-stock-status?attention=1`),
                fetch(`${API}/api/restock-reports?limit=30`)
            ]);
            const status = await statusRes.json();
            const hist = await histRes.json();
            if (!statusRes.ok || !status.success) throw new Error(status.message || 'Failed to load stock status');
            setLive(status);
            setHistory(hist.success ? hist.reports : []);
        } catch (err) {
            showAlert(err.message || 'Could not load the restock report.', 'error');
        } finally {
            setLoading(false);
        }
    }, [showAlert]);

    useEffect(() => { load(); }, [load]);

    const rows = useMemo(() => {
        const all = live.medicines.map(fromLive).sort((a, b) => (STATUS_ORDER[a.status] - STATUS_ORDER[b.status]) || a.name.localeCompare(b.name));
        if (filter === 'expiring') return all.filter((r) => r.expiring > 0);
        if (filter === 'expired') return all.filter((r) => r.expired > 0);
        if (filter === 'Out of stock' || filter === 'Critical' || filter === 'Low') return all.filter((r) => r.status === filter);
        return all;
    }, [live.medicines, filter]);

    const generate = async () => {
        setGenerating(true);
        try {
            const res = await fetch(`${API}/api/restock-reports/generate`, {
                method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ user_id: userId })
            });
            const data = await res.json();
            if (!res.ok || !data.success) throw new Error(data.message || 'Failed to generate the report');
            showAlert(data.new_alerts.length > 0
                ? `Report saved. ${data.new_alerts.length} new stock alert(s) were sent to the nurse and office accounts.`
                : 'Report saved to the history.', 'success');
            load();
        } catch (err) {
            showAlert(err.message, 'error');
        } finally {
            setGenerating(false);
        }
    };

    const viewReport = async (id) => {
        try {
            const res = await fetch(`${API}/api/restock-reports/${id}`);
            const data = await res.json();
            if (!res.ok || !data.success) throw new Error(data.message || 'Report not found');
            setOpenReport(data.report);
        } catch (err) {
            showAlert(err.message, 'error');
        }
    };

    const blocked = () => showAlert('Please allow popups to preview and print the report.', 'warning');
    const s = live.summary;

    const cards = s ? [
        { key: 'Out of stock', label: 'Out of stock', value: s.out, tone: 'out' },
        { key: 'Critical', label: 'Critical', value: s.critical, tone: 'critical' },
        { key: 'Low', label: 'Low', value: s.low, tone: 'low' },
        { key: 'expiring', label: 'Expiring in 30 days', value: s.expiring, tone: 'soon' },
        { key: 'expired', label: 'With expired stock', value: s.expired, tone: 'out' }
    ] : [];

    return (
        <div className="container-rr">
            <header className="header-rr">
                <div>
                    <h2><PackageCheck size={22} /> Restock Report</h2>
                    <p>Medicines that need restocking, checked automatically every morning at 7:00 AM and whenever stock changes. The nurse and office accounts are notified when a medicine gets lower.</p>
                </div>
                <div className="actions-rr">
                    <button className="btn-rr btn-light-rr" onClick={load} title="Refresh"><RefreshCw size={16} /> Refresh</button>
                    <button className="btn-rr btn-light-rr" onClick={generate} disabled={generating}><History size={16} /> {generating ? 'Saving...' : 'Save report now'}</button>
                    <button className="btn-rr btn-primary-rr" onClick={() => printRestock('Current Restock Needs', stamp(live.generated_at), rows, nurseName, blocked)}>
                        <Printer size={16} /> Print / Save as PDF
                    </button>
                </div>
            </header>

            {loading ? <div className="empty-rr">Loading stock levels...</div> : (
                <>
                    <div className="cards-rr">
                        {cards.map((c) => (
                            <button key={c.key} type="button" className={`card-rr card-${c.tone}-rr ${filter === c.key ? 'card-active-rr' : ''}`} onClick={() => setFilter(filter === c.key ? 'all' : c.key)}>
                                <span className="card-value-rr">{c.value}</span>
                                <span className="card-label-rr">{c.label}</span>
                            </button>
                        ))}
                    </div>

                    <section className="section-rr">
                        <div className="section-head-rr">
                            <h3><AlertTriangle size={18} /> Needs attention now {filter !== 'all' && <span className="filter-pill-rr">filtered <button type="button" onClick={() => setFilter('all')} aria-label="Clear filter"><X size={12} /></button></span>}</h3>
                            <span className="muted-rr"><Clock size={13} /> Checked {stamp(live.generated_at)}</span>
                        </div>
                        <RestockTable rows={rows} />
                    </section>

                    <section className="section-rr">
                        <div className="section-head-rr"><h3><History size={18} /> Report history</h3></div>
                        <div className="table-wrap-rr">
                            <table className="table-rr">
                                <thead><tr><th>Generated</th><th>Source</th><th>Out</th><th>Critical</th><th>Low</th><th>Expiring</th><th>Expired</th><th></th></tr></thead>
                                <tbody>
                                    {history.length === 0 ? (
                                        <tr><td colSpan="8" className="empty-rr">No saved reports yet. The first one is saved at 7:00 AM, when a medicine runs low, or when you press &quot;Save report now&quot;.</td></tr>
                                    ) : history.map((r) => (
                                        <tr key={r.report_id}>
                                            <td>{stamp(r.generated_at)}<div className="muted-rr">{r.report_id}</div></td>
                                            <td>{TRIGGER_LABEL[r.trigger_source] || r.trigger_source}</td>
                                            <td>{r.out_count}</td><td>{r.critical_count}</td><td>{r.low_count}</td><td>{r.expiring_count}</td><td>{r.expired_count}</td>
                                            <td><button className="btn-rr btn-light-rr" onClick={() => viewReport(r.report_id)}>View</button></td>
                                        </tr>
                                    ))}
                                </tbody>
                            </table>
                        </div>
                    </section>
                </>
            )}

            {openReport && (
                <div className="modal-overlay-rr" role="dialog" aria-modal="true">
                    <div className="modal-rr">
                        <div className="modal-head-rr">
                            <div>
                                <h3>Restock report {openReport.report_id}</h3>
                                <div className="muted-rr">{stamp(openReport.generated_at)} - {TRIGGER_LABEL[openReport.trigger_source] || openReport.trigger_source}</div>
                            </div>
                            <button className="close-rr" onClick={() => setOpenReport(null)} aria-label="Close"><X size={20} /></button>
                        </div>
                        <RestockTable rows={openReport.items.map(fromItem)} />
                        <div className="modal-foot-rr">
                            <button className="btn-rr btn-light-rr" onClick={() => setOpenReport(null)}>Close</button>
                            <button className="btn-rr btn-primary-rr" onClick={() => printRestock(`Restock Report ${openReport.report_id}`, stamp(openReport.generated_at), openReport.items.map(fromItem), nurseName, blocked)}>
                                <Printer size={16} /> Print / Save as PDF
                            </button>
                        </div>
                    </div>
                </div>
            )}
        </div>
    );
};

export default RestockReport;
